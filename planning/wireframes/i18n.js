const wireframeI18n = (() => {
  const messages = new Map(wireframeMessages.map(([source, en, es]) => [source, { en, es }]));
  const supported = ["pt-BR", "en", "es"];
  const storageKey = "fintalab.wireframes.language";
  let language = "pt-BR";
  try {
    const saved = localStorage.getItem(storageKey);
    if (supported.includes(saved)) language = saved;
  } catch {
    // file:// and privacy policies may block storage; the selector still works.
  }
  const textBindings = [];
  const attributeBindings = [];
  const pixelBindings = [];
  function t(source, parameters = {}) {
    const translated = language === "pt-BR" ? source : messages.get(source)?.[language] || source;
    return translated.replace(/\{(\w+)\}/g, (match, key) => parameters[key] ?? match);
  }
  function init() {
    // Keep source nodes rather than replacing HTML, preserving listeners and form values.
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
      const node = walker.currentNode;
      if (!node.textContent.trim() || node.parentElement.closest(
        "script, style, svg, [data-pixel-text], [data-country-reference], [data-country-select], #language-preview",
      )) continue;
      textBindings.push([node, node.textContent]);
    }
    document.querySelectorAll("[data-pixel-text]").forEach((element) => {
      pixelBindings.push([element, element.textContent.trim()]);
    });
    document.querySelectorAll("*").forEach((element) => {
      for (const name of ["aria-label", "placeholder", "alt", "data-title", "data-label"]) {
        if (element.hasAttribute(name)) attributeBindings.push([element, name, element.getAttribute(name)]);
      }
      if (element.matches('input[type="text"], input:not([type])') && element.hasAttribute("value")) {
        attributeBindings.push([element, "value", element.getAttribute("value")]);
      }
    });
    // Freeze implicit option values before translating their displayed labels.
    document.querySelectorAll("option:not([value])").forEach((option) => { option.value = option.textContent; });
    document.querySelector('meta[name="description"]').dataset.source = document.querySelector('meta[name="description"]').content;
    document.querySelector("#language-preview").addEventListener("change", (event) => setLanguage(event.target.value));
    setLanguage(language, false);
  }
  function setLanguage(next, persist = true) {
    if (!supported.includes(next)) return;
    language = next;
    document.documentElement.lang = language;
    document.querySelector("#language-preview").value = language;
    textBindings.forEach(([node, source]) => {
      node.textContent = source.replace(/\S(?:[\s\S]*\S)?/, (text) => t(text));
    });
    attributeBindings.forEach(([element, name, source]) => element.setAttribute(name, t(source)));
    pixelBindings.forEach(([element, source]) => { element.textContent = t(source); });
    const description = document.querySelector('meta[name="description"]');
    description.content = t(description.dataset.source);
    if (persist) {
      try { localStorage.setItem(storageKey, language); } catch { /* Storage is optional. */ }
    }
    renderCountries();
    document.dispatchEvent(new CustomEvent("wireframe-language-change"));
  }
  return { init, t, setLanguage, messages };
})();
